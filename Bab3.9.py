#Operasi Aritmatika
a=10
b=2
#Operasi Penjumlahan +
hasil = a + b
print(a, '+',b,'=',hasil)
#Operasi Pengurangan -
hasil = a - b
print(a, '-',b,'=',hasil)
#Operasi Perkalian *
hasil = a * b
print(a, '*',b,'=',hasil)
#Operasi Pembagian /
hasil = a / b
print(a, '/',b,'=',hasil)
#Operasi eksponen(pangkat)**
hasil = a ** b
print(a, '**',b,'=',hasil)
#Operasi Modulus (sisa bagi)%
hasil = a % b
print(a, '%',b,'=',hasil)
#Operasi Floor division //
#(KEBALIKAN MODULUS. HASIL BAGI DIBULATKAN KE-BAWAH)
hasil = a // b
print(a, '//',b,'=',hasil)
